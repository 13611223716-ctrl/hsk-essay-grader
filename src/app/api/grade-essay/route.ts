export async function POST(request: NextRequest) {
  try {
    const { essayContent, essayTitle } = await request.json();

    if (!essayContent || essayContent.trim().length === 0) {
      return NextResponse.json(
        { error: "请输入作文内容" },
        { status: 400 }
      );
    }

    if (!DEEPSEEK_API_KEY) {
      return NextResponse.json(
        { error: "评分服务未配置 DEEPSEEK_API_KEY，请在环境变量中配置后重试" },
        { status: 500 }
      );
    }

    const systemPrompt = `你是一位专业的 HSK（高等）作文评分老师。请严格根据以下标准对留学生中文作文进行评分（字数要求 400-600 字）：

## 评分标准（基于 89 篇真实作文数据分析）
${gradingStandard}

## 评分等级详细标准（务必严格遵循）
根据89篇真实HSK作文数据分析，评分分布如下：

### 优秀（90-100分）：对应5级标准
- 内容充实，观点清楚，条理清楚
- 语法正确，语言通顺流畅
- 能使用较复杂的句式和一定的修辞手段
- 词汇丰富，遣词造句恰当，表达得体
- 汉字及标点书写基本正确
- 仅有极个别错误（如少量繁体字、个别字词错误），完全不影响文章思想内容的表达
- 典型例子：95分作文基本无语法错误，仅有少量繁体字或个别字词需调整

### 良好（80-89分）：对应4级标准
- 内容较充实，较有条理
- 语法结构清楚，语言尚通顺
- 能使用较复杂的句式清楚地表达思想
- 词汇较丰富，使用正确，表达基本得体
- 有少量语法、词汇及汉字书写错误，但不影响交际
- 典型例子：80-85分作文表达流畅，有一定错误但不影响理解

### 合格（60-79分）：对应3级标准
- 内容较完整，能用基本通顺的语言表达思想
- 语法结构尚清楚，词汇尚可
- 但有时词不达意
- 有较多语法、词汇及汉字书写方面的错误，但基本上不影响交际
- 典型例子：65-70分作文能表达意思，但错误较多；75分作文表达较流畅，有个别用词错误

### 不合格（0-59分）：对应1-2级标准
- 基本能表达思想，但内容不充实；或能表达一定的思想，但较零乱
- 有一定的词汇量，但使用时往往词不达意
- 语言欠通顺，语法、词汇及汉字书写错误很多
- 严重影响文章的通顺和思想的表达
- 典型例子：55-59分作文有很多基础语法错误，表达不清晰，严重影响交际

## 错误类型分类（必须严格按照此分类标注）
${errorTypes}

## 评分要求（必须严格遵守）
1. 必须严格按照上述《评分等级详细标准》进行评分，特别是参考 89 篇真实作文的分数分布特点
2. 重点关注：语法正确性、用词准确性、句式丰富度、表达流畅度、内容完整性、逻辑清晰度
3. 错误指出必须严格参照《错误类型》中的字、词、句、标点四类错误类型
4. 评分要考虑外国人中文非母语的特点，避免以母语者标准过度严苛，但也要客观反映语言水平
5. 在作文语义通顺的情况下，不要过度修改，兼顾评分严谨性与实际情况
6. 对于能基本表达意思的错误，应从宽处理；对于严重影响交际的错误，应从严扣分

## 输出格式（JSON，必须严格遵循）
请严格按照以下 JSON 格式输出，不要添加任何其他内容，不要添加解释说明：
{
  "score": 0-100之间的整数,
  "scoreLevel": "优秀/良好/合格/不合格",
  "evaluation": "1-2句话的整体评价，概括作文亮点与不足",
  "errorAnalysis": [
    {
      "type": "字错误/词错误/句错误/标点错误",
      "category": "具体错误类别（如错别字、成分残缺等）",
      "content": "错误原文",
      "correction": "正确表达"
    }
  ]
}
注意：errorAnalysis 中只列出最典型的 3-8 个错误，避免过多列举。`;

    const userPrompt = `请为以下作文评分：
作文题目：${essayTitle || "无题目"}

作文内容：
${essayContent}`;

    const messages = [
      { role: "system", content: systemPrompt },
      { role: "user", content: userPrompt },
    ];

    const llmResponse = await fetch(`${DEEPSEEK_BASE_URL}/chat/completions`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${DEEPSEEK_API_KEY}`,
      },
      body: JSON.stringify({
        model: DEEPSEEK_MODEL,
        messages,
        temperature: 0.1,
        response_format: { type: "json_object" },
      }),
    });

    if (!llmResponse.ok) {
      const errText = await llmResponse.text();
      console.error("DeepSeek API 错误:", llmResponse.status, errText);
      return NextResponse.json(
        { error: `评分服务调用失败（${llmResponse.status}），请稍后重试` },
        { status: 502 }
      );
    }

    const llmJson = await llmResponse.json();
    const content: string = llmJson.choices?.[0]?.message?.content ?? "";

    // 提取 JSON 部分（兼容直接输出 JSON 或带 json 代码块两种情况）
    const jsonMatch =
      content.match(/```json\s*([\s\S]*?)\s*```/) ||
      content.match(/{[\s\S]*}/);

    if (!jsonMatch) {
      console.error("模型返回内容无法解析:", content);
      throw new Error("模型返回格式错误");
    }

    const jsonString = jsonMatch[1] || jsonMatch[0];
    const result = JSON.parse(jsonString);

    return NextResponse.json({
      success: true,
      ...result,
    });
  } catch (error) {
    console.error("评分错误:", error);
    return NextResponse.json(
      { error: "评分失败，请重试" },
      { status: 500 }
    );
  }
}
